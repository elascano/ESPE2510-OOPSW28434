    public void showLowStockAlert(Product product, int minStock) {
        JOptionPane.showMessageDialog(
                null,
                "LOW STOCK ALERT\n\n"
                + "Product: " + product.getName() + "\n"
                + "Current stock: " + product.getStock() + "\n"
                + "Minimum allowed: " + minStock,
                "Alarm",
                JOptionPane.WARNING_MESSAGE
        );
    }

