    private void jTextFieldTotalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jTextFieldTotalActionPerformed
     try {
        // Leer el total ingresado
        double total = Double.parseDouble(jTextFieldTotal.getText());

        // Obtener el descuento actual de la sesión
        Discount currentDiscount = DiscountSession.getInstance().getCurrentDiscount();
        double percentage = currentDiscount.getPercentage();

        // Calcular el total con descuento
        double discountedTotal = total - (total * percentage / 100);

        // Mostrar resultado en mensaje
        javax.swing.JOptionPane.showMessageDialog(this, 
            "Original total: $" + total + "\n" +
            "Discount: " + percentage + "%\n" +
            "Total after discount: $" + discountedTotal
        );

        // Guardar el descuento en JSON
        JsonUtil.saveJSON("Discount.json", currentDiscount);

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid number.");
    }
    }//GEN-LAST:event_jTextFieldTotalActionPerformed

