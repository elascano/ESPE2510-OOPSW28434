    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
     int selected = Integer.parseInt((String) cmbOptions.getSelectedItem());
    Discount discount = new Discount(selected);
    DiscountSession.getInstance().setCurrentDiscount(discount);

    // Mostrar en textarea
    txaReadDisccount.setText("Current Discount: " + selected + "%");

    // Guardar en JSON
    JsonUtil.saveJSON("Discount.json", discount);

    }//GEN-LAST:event_btnSaveActionPerformed

