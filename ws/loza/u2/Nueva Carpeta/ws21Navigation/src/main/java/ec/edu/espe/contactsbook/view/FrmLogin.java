    private void btnAcceptActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAcceptActionPerformed
        String userName = txtUser.getText();
        String password = passPassword.getText();

        User user = new User(userName, password, "family");

        if (UserController.validateLogin(user)) {
            FrmContactsMenu contacts = new FrmContactsMenu();
            contacts.setVisible(true);
           
            lblErrorMessage.setForeground(Color.black);
            lblErrorMessage.setText("Welcome");
            this.setVisible(false);

        } else {
            lblErrorMessage.setForeground(Color.red);
            lblErrorMessage.setText("Either user name opr password is wrong]");
        }
    }//GEN-LAST:event_btnAcceptActionPerformed

