    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
 try {
        String[] input = jTextField1.getText().split(",");
        int[] data = new int[input.length];

        for (int i = 0; i < input.length; i++) {
            data[i] = Integer.parseInt(input[i].trim());
        }

        SortController controller = new SortController();
        int[] sortedList = controller.sortData(data);

        JOptionPane.showMessageDialog(this, "your numbers order are: " + Arrays.toString(sortedList));

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Invalid format. Use numbers separated by commas.");
    }

    }//GEN-LAST:event_jButton1ActionPerformed

    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
   try {
        String[] input = jTextField1.getText().split(",");
        int[] unsortedData = new int[input.length];

        for (int i = 0; i < input.length; i++) {
            unsortedData[i] = Integer.parseInt(input[i].trim());
        }

        SortController controller = new SortController();
        int[] sortedData = controller.sortData(unsortedData); 

        controller.saveToMongo(unsortedData, sortedData);

        javax.swing.JOptionPane.showMessageDialog(this, "Saved to StrategyChalan DB!\n"
                + "Algorithm: " + ((unsortedData.length < 30) ? "BubbleSort" : "QuickSort") + "\n"
                + "Sorted: " + java.util.Arrays.toString(sortedData));

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Error: Check the input format.");
    }

    }//GEN-LAST:event_jButton2ActionPerformed

