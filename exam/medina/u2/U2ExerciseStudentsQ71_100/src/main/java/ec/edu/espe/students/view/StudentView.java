    private void btnDeleteStudentActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteStudentActionPerformed
String idText = txtId.getText().trim();

        if (idText.isEmpty() || idText.equals("Enter the ID")) {
            JOptionPane.showMessageDialog(this, "Please enter a valid Student ID.", "Validation", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int option = JOptionPane.showConfirmDialog(this, 
                "Are you sure you want to delete this student?", 
                "Confirm Delete", 
                JOptionPane.YES_NO_OPTION);

        if (option == JOptionPane.YES_OPTION) {
            try {
                boolean success = controller.deleteStudent(idText);

                if (success) {
                    JOptionPane.showMessageDialog(this, 
                            "Student deleted successfully!", 
                            "Success", 
                            JOptionPane.INFORMATION_MESSAGE);
                    txtId.setText(""); 
                } else {
                    JOptionPane.showMessageDialog(this, 
                            "Could NOT delete student.\nPossible reasons:\n1. ID not found.\n2. Student is under 18 years old.", 
                            "Error", 
                            JOptionPane.ERROR_MESSAGE);
                }
            } catch (IllegalArgumentException e) {
                JOptionPane.showMessageDialog(this, 
                        "Invalid ID format. Must be a MongoDB ObjectId.", 
                        "Format Error", 
                        JOptionPane.ERROR_MESSAGE);
            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, 
                        "An error occurred: " + e.getMessage(), 
                        "Error", 
                        JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_btnDeleteStudentActionPerformed

