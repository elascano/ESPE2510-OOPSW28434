    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
       raedValues();
        int option = javax.swing.JOptionPane.showConfirmDialog(
                this, 
                "Saving contact", 
                "CONTACTS", 
                javax.swing.JOptionPane.YES_NO_CANCEL_OPTION
        );

        if (option == javax.swing.JOptionPane.YES_OPTION) {

            com.mongodb.client.MongoDatabase database = ec.edu.espe.contactsbook.utils.MongoConnection.getDatabase();
            com.mongodb.client.MongoCollection<org.bson.Document> collection =
                    database.getCollection("ContactsJava");

            org.bson.Document doc = new org.bson.Document()
            .append("firstName", contact.getFirstName())
            .append("lastName", contact.getLastName())
            .append("birthDate", contact.getBirthDate())
            .append("age", contact.getAge())
            .append("type", contact.getTypeOfContact())
            .append("sex", contact.getSex())
            .append("hobbies", contact.getHobbies())
            .append("comments", contact.getComments());


            collection.insertOne(doc);

            javax.swing.JOptionPane.showMessageDialog(this, "Your contact is saved");
            emptyFields();

        } else if (option == javax.swing.JOptionPane.NO_OPTION) {

            javax.swing.JOptionPane.showMessageDialog(this, "Your data will be lost");
            emptyFields();

        } else {
            txtFirstName.requestFocus();
        }
    }//GEN-LAST:event_btnSaveActionPerformed

    private void emptyFields(){
    
        txtFirstName.setText("");
        txtLastName.setText("");
        ftdBirthDate.setText("");
        cmbType.setSelectedIndex(0);
        radSexFemale.setSelected(true);
        lstHobbie.clearSelection();
        txaComments.setText("");
        
    }
    
    private void raedValues() {
        String firstName = txtFirstName.getText();
        String lastName = txtLastName.getText();

        String birthDate = ftdBirthDate.getDate() != null
                ? ftdBirthDate.getDate().toString()
                : "";

        int age = 19;

        String typeOfContact = cmbType.getSelectedItem().toString();

        String sex;
        if (radSexMale.isSelected()) {
            sex = "Male";
        } else {
            sex = "Female";
        }

        ArrayList<String> hobbies = new ArrayList<>();
        hobbies.addAll(lstHobbie.getSelectedValuesList());

        String comments = txaComments.getText();

        contact = new Contact(age, firstName, lastName, birthDate, age, typeOfContact, sex, hobbies, comments);
    }


