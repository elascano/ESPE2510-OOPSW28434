    private void txtSearchIdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtSearchIdActionPerformed
        // TODO add your handling code here:
        tableModel.setRowCount(0);
        tableModel.setColumnCount(0);

        String id = txtSearchId.getText().trim();
        if (id.isEmpty() || !id.matches("\\d+")) {
            JOptionPane.showMessageDialog(this, "ID must contain only numbers");
            return;
        }

        Product entity = controller.getById(id);
        if (entity == null) {
            JOptionPane.showMessageDialog(this, "No data found for ID: " + id);
            return;
        }

        tableModel.addColumn("ID");
        for (String key : entity.getAttributes().keySet()) {
            tableModel.addColumn(key);
        }

        Vector<Object> row = new Vector<>();
        row.add(entity.getId());
        for (Object value : entity.getAttributes().values()) {
            row.add(value);
        }
        tableModel.addRow(row);
    }//GEN-LAST:event_txtSearchIdActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        // TODO add your handling code here:
        tableModel.setRowCount(0);
        tableModel.setColumnCount(0);

        String id = txtSearchId.getText().trim();
        if (id.isEmpty()) {
            return;
        }

        Product entity = controller.getById(id);
        if (entity == null) {
            return;
        }

        tableModel.addColumn("ID");
        for (String key : entity.getAttributes().keySet()) {
            tableModel.addColumn(key);
        }

        Vector<Object> row = new Vector<>();
        row.add(entity.getId());
        for (Object value : entity.getAttributes().values()) {
            row.add(value);
        }
        tableModel.addRow(row);
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnLoadAllActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoadAllActionPerformed
        // TODO add your handling code here:
        tableModel.setRowCount(0);
        tableModel.setColumnCount(0);

        List<Product> entities = controller.getAll();
        if (entities == null || entities.isEmpty()) {
            return;
        }

        tableModel.addColumn("ID");
        for (String key : entities.get(0).getAttributes().keySet()) {
            tableModel.addColumn(key);
        }

        for (Product entity : entities) {
            Vector<Object> row = new Vector<>();
            row.add(entity.getId());
            for (Object value : entity.getAttributes().values()) {
                row.add(value);
            }
            tableModel.addRow(row);
        }
    }//GEN-LAST:event_btnLoadAllActionPerformed

