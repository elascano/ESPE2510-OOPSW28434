    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        // TODO add your handling code here:                                    
        String id = txtId.getText();
        String product = txtKey.getText().trim();
        String priceText = txtValue.getText().trim();

        if (product.isEmpty() || priceText.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Product and Price are required");
            return;
        }

        double price;
        try {
            price = Double.parseDouble(priceText);
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Price must be a number");
            return;
        }

        double priceTotal = price * 1.15;

        JOptionPane.showMessageDialog(
            this,
            "Final price with IVA (15%): $" + String.format("%.2f", priceTotal)
        );

        Map<String, Object> attributes = new HashMap<>();
        attributes.put("Product", product);
        attributes.put("Price", price);
        attributes.put("PriceTotal", priceTotal);

        Product entity = new Product(id, attributes);

        if (controller.create(entity)) {
            JOptionPane.showMessageDialog(this, "Data added successfully");
            txtKey.setText("");
            txtValue.setText("");
            loadNextId();
        } else {
            JOptionPane.showMessageDialog(this, "Error saving data");
        }
    }//GEN-LAST:event_btnAddActionPerformed

