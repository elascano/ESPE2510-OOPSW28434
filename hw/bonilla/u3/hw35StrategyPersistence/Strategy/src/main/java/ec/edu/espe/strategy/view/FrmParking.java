    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed
        // TODO add your handling code here:
        String id = txtId.getText().trim();
        String plate = txtPlate.getText().trim().toUpperCase();
        String type = cmbType.getSelectedIndex() > 0 ? cmbType.getSelectedItem().toString() : "";

        if(id.isEmpty() || plate.isEmpty() || type.isEmpty()){
            javax.swing.JOptionPane.showMessageDialog(this, "ID, Plate, and Type are required!");
            return;
        }

        if(!plate.matches("[A-Z]{3}-\\d{4}")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Invalid plate format! Use ABC-1234");
            return;
        }

        LocalDateTime entry;
        try {
            entry = txtEntry.getText().isEmpty() 
                    ? LocalDateTime.now() 
                    : LocalDateTime.parse(txtEntry.getText());
        } catch(Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Entry time format is invalid! Use yyyy-MM-ddTHH:mm:ss");
            return;
        }

        boolean success = controller.registerEntry(id, plate, type, entry);
        if(!success) {
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to register entry. Check your strategy.");
            return;
        }

        txtId.setText(controller.getNextId());
        txtPlate.setText("");
        txtEntry.setText(LocalDateTime.now().toString());
        txtExit.setText("");
        txtFee.setText("");
        cmbType.setSelectedIndex(0);
        loadTable();
    }//GEN-LAST:event_btnCreateActionPerformed

