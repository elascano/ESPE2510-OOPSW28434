    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        // TODO add your handling code here:
        String id = txtId.getText().trim();
        Parking p = controller.findById(id);
        if(p != null){
            String plate = txtPlate.getText().trim();
            String type = cmbType.getSelectedIndex() > 0 ? cmbType.getSelectedItem().toString() : "";
            if(plate.isEmpty() || type.isEmpty()){
                javax.swing.JOptionPane.showMessageDialog(this, "Plate and Type are required!");
                return;
            }

            LocalDateTime entry;
            LocalDateTime exit = null;
            double fee = 0;

            try {
                entry = LocalDateTime.parse(txtEntry.getText());
                if(!txtExit.getText().isEmpty()){
                    exit = LocalDateTime.parse(txtExit.getText());
                    if(exit.isBefore(entry)){
                        javax.swing.JOptionPane.showMessageDialog(this, "Exit time must be after entry time!");
                        return;
                    }
                    fee = Double.parseDouble(txtFee.getText());
                    if(fee < 0){
                        javax.swing.JOptionPane.showMessageDialog(this, "Fee must be positive!");
                        return;
                    }
                }
            } catch(Exception e){
                javax.swing.JOptionPane.showMessageDialog(this, "Date/time format is invalid! Use yyyy-MM-ddTHH:mm:ss");
                return;
            }

            p.setPlate(plate);
            p.setVehicleType(type);
            p.setEntryTime(entry);
            p.setExitTime(exit);
            p.setFee(fee);
            controller.registerExit(id); 
            loadTable();
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

