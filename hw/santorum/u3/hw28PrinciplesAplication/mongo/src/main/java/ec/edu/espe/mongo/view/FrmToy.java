    private void btnLoadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoadActionPerformed
    DefaultTableModel model = (DefaultTableModel) tblToy.getModel();
    model.setRowCount(0);

    List<Toy> toys = toyController.findAll();

    for (Toy toy : toys) {
        model.addRow(new Object[]{
            toy.getId(),
            toy.getName(),
            toy.getPrice(),
            toy.getPriceIva()
        });
    }
    }//GEN-LAST:event_btnLoadActionPerformed

    private void addStoreToTable(Toy store) {
        DefaultTableModel model = (DefaultTableModel) tblToy.getModel();

        model.addRow(new Object[]{
            store.getId(),
            store.getName(),
            String.format("%.2f", store.getPrice()),
            String.format("%.2f", store.getPriceIva())
        });
    }

    private void clearTable() {
        DefaultTableModel model = (DefaultTableModel) tblToy.getModel();
        model.setRowCount(0);
    }

