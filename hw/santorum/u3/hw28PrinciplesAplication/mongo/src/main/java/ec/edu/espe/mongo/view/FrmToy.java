    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed


    int id = Integer.parseInt(txtId.getText());
    Toy toy = toyController.findById(id);

    clearTable();

    if (toy != null) {
        txtName.setText(toy.getName());
        txtPrice.setText(String.valueOf(toy.getPrice()));
        txtPriceIva.setText(String.valueOf(toy.getPriceIva()));
        addStoreToTable(toy);
    } else {
        JOptionPane.showMessageDialog(this, "Toy not found");
    }



    }//GEN-LAST:event_btnFindActionPerformed

