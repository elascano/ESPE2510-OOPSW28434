    private void ftdBirthDateKeyReleased(java.awt.event.KeyEvent evt) {//GEN-FIRST:event_ftdBirthDateKeyReleased
  String fechaTexto = ftdBirthDate.getText().trim();

if (fechaTexto.matches("\\d{2}/\\d{2}/\\d{4}")) {
    try {
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy");
        LocalDate fechaNac = LocalDate.parse(fechaTexto, formatter);

        int edad = Period.between(fechaNac, LocalDate.now()).getYears();

        txtAge.setText(String.valueOf(edad));

    } catch (Exception e) {
        txtAge.setText("");
    }
} else {
    txtAge.setText("");
}

    }//GEN-LAST:event_ftdBirthDateKeyReleased

