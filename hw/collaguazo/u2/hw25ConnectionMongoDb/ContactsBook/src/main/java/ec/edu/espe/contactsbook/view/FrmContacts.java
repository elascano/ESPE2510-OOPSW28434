    private String getContactInfo(Contact c){
        
        StringBuilder sb= new StringBuilder();
        sb.append("ID: ").append(c.getId()).append("\n");
        sb.append("Name: ").append(c.getFirstName()).append("\n");
        sb.append("ID: ").append(c.getLastName()).append("\n");
        sb.append("Age: ").append(c.getAge()).append("\n");
        sb.append("Type: ").append(c.getTypeOfContact()).append("\n");
        sb.append("Sex: ").append(c.getSex()).append("\n");
        sb.append("Fecha de nacimiento: ").append(c.getBirthDate()).append("\n");
        sb.append("Hobbies : ").append(c.getHobbies()).append("\n");
        sb.append("Comentarios : ").append(c.getComments()).append("\n");
        
        
        return sb.toString();
    }
    
    private void showContacts(){
        
        ContactDao dao = new ContactDao();
        
        ArrayList<Contact>contacts=dao.getAllContacts();
        
        if (contacts.isEmpty()){
            JOptionPane.showMessageDialog(this, "No hay contactos guardados.", "Ver Contactos", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        
        StringBuilder sb = new StringBuilder();
        SimpleDateFormat sdf = new SimpleDateFormat("dd/MM/yyyy");
        
        for (Contact c : contacts){
          sb.append("ID: ").append(c.getId())    
            .append("\nNombre: ").append(c.getFirstName())
            .append("\nApellido: ").append(c.getLastName())
            .append("\nBirth Date: ").append(sdf.format(c.getBirthDate()))
            .append("\nEdad: ").append(c.getAge())
            .append("\nTipo: ").append(c.getTypeOfContact())
            .append("\nSexo: ").append(c.getSex())
            .append("\nHobbies: ").append(c.getHobbies())
            .append("\nComentarios: ").append(c.getComments())
            .append("\n--------------------------\n");
           
          
        }
        JOptionPane.showMessageDialog(this, sb.toString(), "Contactos Guardados", JOptionPane.INFORMATION_MESSAGE);
        
    }
    

