    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
         Contact contact = readValues();

    if (contact == null) {
        return; // si falta algún dato, no continua
    }

    int option = JOptionPane.showConfirmDialog(
        this,
        "Guardar contacto: " + contact.getFirstName(),
        "Confirmación",
        JOptionPane.YES_NO_OPTION
    );

    if (option == JOptionPane.YES_OPTION) {

        ContactDao dao = new ContactDao();
        dao.insert(contact);

        // ************************************************************
        // *************   GUARDAR TAMBIÉN EN MONGODB   ***************
        // ************************************************************
        guardarEnMongo(contact);
        // ************************************************************

        ArrayList<Contact> contacts = dao.getAllContacts();
        ContactsJson.saveContactsToJson(contacts);

        JOptionPane.showMessageDialog(
            this,
            getContactInfo(contact),
            "Contacto guardado correctamente",
            JOptionPane.INFORMATION_MESSAGE
        );

        emptyFields();
    }
      
    }//GEN-LAST:event_btnSaveActionPerformed

