    private Contact readValues() {

        String firstName = txtFirstName.getText();
        String lastName = txtLastName.getText();
        Date birthDate = jDateChooserBirthday.getDate();
        String ageText = txtAge.getText();
        String typeOfContact = cmbType.getSelectedItem().toString();
        String sex = radSexMale.isSelected() ? "Male" : "Female";
        ArrayList<String> hobbiesList = new ArrayList<>(jListHobbies.getSelectedValuesList());
        String comments = txaComments.getText();
        
        if(!ContactValidator.isNameValid(firstName)){
            JOptionPane.showMessageDialog(this, "Ingrese un nombre valido");
            return null;
        }
        
        if (!ContactValidator.isLasteNameValid(lastName)){
            JOptionPane.showMessageDialog(this, "Ingrese un apellido valido");
            return null;
        }
        
        if(!ContactValidator.isBirthDateSelected(birthDate)){
            JOptionPane.showMessageDialog(this, "Ingrese una fecha valida");
            return null;
        }
        
        if(!ContactValidator.isAgeValid(ageText)){
          
            JOptionPane.showMessageDialog(this, "Edad no valida");
            return  null;
        }
        
        int age = Integer.parseInt(ageText);
        
        // id no se obtiene del formulario, se generará después
        return new Contact(0, firstName,lastName,birthDate, age , typeOfContact, sex, hobbiesList, comments);
    }
   
