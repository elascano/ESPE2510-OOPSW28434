    private void btnUpdateDiscountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateDiscountActionPerformed
        try {
            double newDiscount = Double.parseDouble(txtDiscount.getText());
            controller.updateDiscount(newDiscount);

            JOptionPane.showMessageDialog(
                this,
                "Discount updated successfully"
            );

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                this,
                "Invalid discount value",
                "Error",
                JOptionPane.ERROR_MESSAGE
            );
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(
                this,
                e.getMessage(),
                "Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnUpdateDiscountActionPerformed

    private void txtCalculateTotalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtCalculateTotalActionPerformed
        event.setNameEvent(txtEventName.getText());
        event.setPrice(Double.parseDouble(txtPrice.getText()));

        double total = controller.calculateTotal(event);
        try{
        JOptionPane.showMessageDialog(
            this,
            "Event: " + event.getNameEvent()
            + "\nDiscount: " + controller.getDiscount() + "%"
            + "\nTotal: $" + total
            );

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(
                this,
                "Invalid price",
                "Error",
                JOptionPane.ERROR_MESSAGE
            );
        }   
    }//GEN-LAST:event_txtCalculateTotalActionPerformed

