    private void loadTableData() {
        DefaultTableModel model = (DefaultTableModel) tblBooks.getModel();
        model.setRowCount(0);

        for (Document document : controller.listComputers()) {
            model.addRow(new Object[]{
                document.getString("title"),
                "$" + document.get("daily_fee"),
                document.get("delay_days"),
                "$" + document.get("tax"),
                "$" + document.get("total")
            });
        }
    }

    private void clearFields() {
        txtTitle.setText("");
        txtDailyFee.setText("");
        txtDelayDays.setText("");
        txtTitle.requestFocus();
    }

