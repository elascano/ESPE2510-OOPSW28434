    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        try {
            String title = txtTitle.getText().trim();
            double fee = Double.parseDouble(txtDailyFee.getText());
            int days = Integer.parseInt(txtDelayDays.getText());

            if (title.isEmpty()) {
                JOptionPane.showMessageDialog(this, "Title cannot be empty");
                return;
            }

            boolean success = controller.saveRegistry(title, fee, days);

            if (success) {
                JOptionPane.showMessageDialog(this, "Registry Saved Successfully!");
                clearFields();
                loadTableData();
            } else {
                JOptionPane.showMessageDialog(this, "Error saving to MongoDB", "Database Error", JOptionPane.ERROR_MESSAGE);
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Please enter valid numeric values for Fee and Days", "Input Error", JOptionPane.WARNING_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveActionPerformed

