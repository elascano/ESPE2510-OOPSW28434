   private void cargarProductosDesdeMongo() {
        ProductDao dao = new ProductDao();
        ArrayList<Product> products = dao.getAllProducts();

        StringBuilder texto = new StringBuilder();
        for (Product p : products) {
            texto.append("ID: ").append(p.getId()).append("\n");
            texto.append("Producto: ").append(p.getName()).append("\n");
            texto.append("Cantidad: ").append(p.getQuantity()).append("\n");
            texto.append("Precio: ").append(p.getPrice()).append("\n");
            texto.append("Subtotal: ").append(String.format("%.2f", p.getSubtotal())).append("\n");
            texto.append("IVA: ").append(String.format("%.2f", p.getIva())).append("\n");
            texto.append("Total: ").append(String.format("%.2f", p.getTotal())).append("\n");
            texto.append("----------------------------\n");
        }
        txtareaproducts.setText(texto.toString());
    }


   private void calcularTotales() {
        try {
            int cantidad = Integer.parseInt(txtcantidad.getText());
            double precio = Double.parseDouble(txtprice.getText());

            double subtotal = cantidad * precio;
            double iva = subtotal * IVA;
            double total = subtotal + iva;

            txtsubtotal.setText(String.format("%.2f", subtotal));
            txtiva.setText(String.format("%.2f", iva));
            txttotal.setText(String.format("%.2f", total));
        } catch (NumberFormatException e) {
            txtsubtotal.setText("0.00");
            txtiva.setText("0.00");
            txttotal.setText("0.00");
        }
    }




