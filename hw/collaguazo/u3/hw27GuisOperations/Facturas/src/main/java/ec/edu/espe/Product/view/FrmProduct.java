    private void cargarProductos() {
        try {
        ProductDao dao = new ProductDao();
        ArrayList<Product> products = dao.getAllProducts();

        txtareaproducts.setText(""); // limpiar JTextArea

        for (Product p : products) {
            txtareaproducts.append("ID: " + p.getId() + "\n");
            txtareaproducts.append("Nombre: " + p.getName() + "\n");
            txtareaproducts.append("Cantidad: " + p.getQuantity() + "\n");
            txtareaproducts.append("Precio: " + p.getPrice() + "\n");
            txtareaproducts.append("Subtotal: " + p.getSubtotal() + "\n");
            txtareaproducts.append("IVA: " + p.getIva() + "\n");
            txtareaproducts.append("Total: " + p.getTotal() + "\n");
            txtareaproducts.append("---------------------------\n");
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error cargando productos: " + e.getMessage());
    }
}
    
      
      

    private void guardarProducto() {
         try {
        // 1️⃣ Leer datos de los campos de texto
        String nombre = txtname.getText();
        int cantidad = Integer.parseInt(txtcantidad.getText());
        double precio = Double.parseDouble(txtprice.getText());

        // 2️⃣ Crear el objeto Product
        Product product = new Product(nombre, cantidad, precio);
        product.calculateValues(); // recalcula subtotal, iva y total

        // 3️⃣ Guardar en MongoDB
        ProductDao dao = new ProductDao();
        dao.insert(product);

        JOptionPane.showMessageDialog(this, "Producto guardado correctamente");

        // 4️⃣ Mostrar todos los productos en el JTextArea
        cargarProductosDesdeMongo();

        // 5️⃣ Limpiar campos de entrada
        txtname.setText("");
        txtcantidad.setText("");
        txtprice.setText("");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Cantidad y Precio deben ser números válidos");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al guardar el producto: " + e.getMessage());
    }
}

    private void eliminarProducto() {
          try {
        // 1️⃣ Pedir al usuario el ID del producto a eliminar
        String idStr = JOptionPane.showInputDialog(this, "Ingrese el ID del producto a eliminar:");
        if (idStr == null || idStr.isEmpty()) {
            return; // usuario canceló o dejó vacío
        }

        int id = Integer.parseInt(idStr);

        // 2️⃣ Llamar a ProductDao para eliminar
        ProductDao dao = new ProductDao();
        dao.delete(id);

        JOptionPane.showMessageDialog(this, "Producto eliminado correctamente");

        // 3️⃣ Volver a cargar los productos en el JTextArea
        cargarProductosDesdeMongo();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "ID inválido. Debe ser un número entero.");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al eliminar el producto: " + e.getMessage());
    }
}
   
        
