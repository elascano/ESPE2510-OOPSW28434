private void cargarNotebooks() {
        try {
        NotebookDao dao = new NotebookDao();
        ArrayList<Notebook> notebooks = dao.getAllNotebooks();

        txtareanotebooks.setText(""); // limpiar JTextArea

        for (Notebook p : notebooks) {
            txtareanotebooks.append("ID: " + p.getId() + "\n");
            txtareanotebooks.append("Nombre: " + p.getName() + "\n");
            txtareanotebooks.append("Cantidad: " + p.getQuantity() + "\n");
            txtareanotebooks.append("Precio: " + p.getPrice() + "\n");
            txtareanotebooks.append("Subtotal: " + p.getSubtotal() + "\n");
            txtareanotebooks.append("IVA: " + p.getIva() + "\n");
            txtareanotebooks.append("Total: " + p.getTotal() + "\n");
            txtareanotebooks.append("---------------------------\n");
        }
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error cargando productos: " + e.getMessage());
    }
}
    
      

    private void guardarNotebook() {
         try {
        
        String nombre = txtname.getText();
        int cantidad = Integer.parseInt(txtcantidad.getText());
        double precio = Double.parseDouble(txtprice.getText());

        // 2️⃣ Crear el objeto Product
        Notebook notebook = new Notebook(nombre, cantidad, precio);
        notebook.calculateValues(); // recalcula subtotal, iva y total

        // 3️⃣ Guardar en MongoDB
        NotebookDao dao = new NotebookDao();
        dao.insert(notebook);

        JOptionPane.showMessageDialog(this, "Producto guardado correctamente");

        cargarNotebooksDesdeMongo();
        txtname.setText("");
        txtcantidad.setText("");
        txtprice.setText("");

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "Cantidad y Precio deben ser números válidos");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al guardar el producto: " + e.getMessage());
    }
}

    private void eliminarNotebook() {
          try {
        
        String idStr = JOptionPane.showInputDialog(this, "Ingrese el ID del producto a eliminar:");
        if (idStr == null || idStr.isEmpty()) {
            return; //  
        }

        int id = Integer.parseInt(idStr);

      
        NotebookDao dao = new NotebookDao();
        dao.delete(id);

        JOptionPane.showMessageDialog(this, "Producto eliminado correctamente");

        // 3️⃣ Volver a cargar los productos en el JTextArea
        cargarNotebooksDesdeMongo();

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "ID inválido. Debe ser un número entero.");
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al eliminar el producto: " + e.getMessage());
    }
}
   
        
