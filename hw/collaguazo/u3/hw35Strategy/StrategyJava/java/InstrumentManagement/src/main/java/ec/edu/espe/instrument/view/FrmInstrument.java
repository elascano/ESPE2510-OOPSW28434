    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed
        try {
            String id = txtId.getText();
            String name = txtName.getText();
            double price = Double.parseDouble(txtBasePrice.getText());
            List<String> materials = convertTextToList(txtMaterials.getText());

            if (controller.createSculpture(id, name, price, materials)) {
                JOptionPane.showMessageDialog(this, "Instrument Saved");
                clearForm();
                loadTableData(null);
            } else {
                JOptionPane.showMessageDialog(this, "Error: Duplicate ID?");
            }
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Price must be a number");
        }
    }//GEN-LAST:event_btnCreateActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        DefaultTableModel model = (DefaultTableModel) tblInstrument.getModel();
        if (tblInstrument.isEditing()) {
            tblInstrument.getCellEditor().stopCellEditing();
        }

        if (model.getRowCount() == 0) {
            return;
        }

        for (int i = 0; i < model.getRowCount(); i++) {
            try {
                String id = String.valueOf(model.getValueAt(i, 0));
                String name = String.valueOf(model.getValueAt(i, 1));
                String matText = String.valueOf(model.getValueAt(i, 2));
                double price = Double.parseDouble(model.getValueAt(i, 3).toString());

                List<String> matList = convertTextToList(matText);

                controller.updateSculpture(id, name, price, matList);

            } catch (Exception e) {
                System.out.println("Error en fila " + i);
            }
        }
        JOptionPane.showMessageDialog(this, "Table Updated Successfully");
        loadTableData(null);
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int selectedRow = tblInstrument.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Select a row to delete");
            return;
        }
        if (tblInstrument.isEditing()) {
            tblInstrument.getCellEditor().stopCellEditing();
        }

        String id = tblInstrument.getValueAt(selectedRow, 0).toString();

        if (JOptionPane.showConfirmDialog(this, "Delete ID: " + id + "?") == 0) {
            if (controller.deleteSculpture(id)) {
                JOptionPane.showMessageDialog(this, "Deleted!");
                loadTableData(null);
            }
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed
        String id = txtId.getText();
        if (id.isEmpty()) {
            loadTableData(null);
        } else {
            Instrument s = controller.findSculptureById(id);
            if (s != null) {
                List<Instrument> list = new ArrayList<>();
                list.add(s);
                loadTableData(list);
            } else {
                JOptionPane.showMessageDialog(this, "Not Found");
                loadTableData(null);
            }
        }
    }//GEN-LAST:event_btnFindActionPerformed

