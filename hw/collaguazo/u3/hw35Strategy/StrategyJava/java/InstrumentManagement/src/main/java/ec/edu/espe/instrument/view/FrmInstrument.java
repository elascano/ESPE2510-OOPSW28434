    private void loadTableData(List<Instrument> data) {
    DefaultTableModel model = (DefaultTableModel) tblInstrument.getModel();
    model.setRowCount(0);

    List<Instrument> list = (data == null) ? controller.getAllTools() : data;

    for (Instrument string : list) {
        Object[] row = {
            string.getId(),
            string.getName(),
            String.join(", ", string.getMaterials()),
            string.getPrice(),
            string.getPriceWithIva()
        };
        model.addRow(row);
    }
}

    private List<String> convertTextToList(String textWithCommas) {

    if (textWithCommas == null || textWithCommas.trim().isEmpty()) {
        return new ArrayList<>();
    }

    String[] rawItems = textWithCommas.split(",");

    List<String> cleanList = new ArrayList<>();

    for (String item : rawItems) {
        String cleanItem = item.trim();

        if (!cleanItem.isEmpty()) {
            cleanList.add(cleanItem);
        }
    }

    return cleanList;
}

