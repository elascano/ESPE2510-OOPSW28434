private void loadTableFromDatabase() {
    DefaultTableModel model = (DefaultTableModel) jTable1.getModel();
    model.setRowCount(0);

    for (var cellphone : controller.findAll()) {
        model.addRow(new Object[]{
            cellphone.getId(),
            cellphone.getModel(),
            cellphone.getPrice()
        });
    }

    jLabel2labelwillshowstatus.setText("Table synchronized with database");
}


