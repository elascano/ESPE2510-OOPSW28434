    private void jToggleButton2deleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton2deleteActionPerformed

    int row = jTable1.getSelectedRow();
    if (row == -1) {
        jLabel2labelwillshowstatus.setText("Select a row first");
        return;
    }

    String id = jTable1.getValueAt(row, 0).toString();

    controller.delete(id);

    loadTableFromDatabase(); 


    }//GEN-LAST:event_jToggleButton2deleteActionPerformed

    private void jToggleButton1updateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton1updateActionPerformed

    int row = jTable1.getSelectedRow();
    if (row == -1) {
        jLabel2labelwillshowstatus.setText("Select a row first");
        return;
    }

    String id = jTable1.getValueAt(row, 0).toString();
    String model = jTable1.getValueAt(row, 1).toString();
    double price = Double.parseDouble(jTable1.getValueAt(row, 2).toString());

    controller.update(id, model, price);

    loadTableFromDatabase(); 


    }//GEN-LAST:event_jToggleButton1updateActionPerformed

