    private void btnViewVideoCallsActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnViewVideoCallsActionPerformed
        // Obtener todos los registros desde VideoCallDAO
        List<VideoCall> calls = VideoCallDAO.getAllVideoCalls(); // Debes tener este método en tu DAO

        if (calls.isEmpty()) {
            JOptionPane.showMessageDialog(this, "No hay videollamadas registradas.");
            return;
        }

        // Construir el texto para mostrar
        StringBuilder sb = new StringBuilder();
        for (VideoCall call : calls) {
            sb.append("Call ID: ").append(call.getCallId()).append("\n")
              .append("Cliente: ").append(call.getCustomerName()).append("\n")
              .append("Fecha: ").append(call.getVideoCallDate()).append("\n")
              .append("Hora: ").append(call.getVideoCallHour()).append("\n")
              .append("Plataforma: ").append(call.getMedium()).append("\n")
              .append("Nota: ").append(call.getNote()).append("\n")
              .append("-----------------------------\n");
        }

        // Mostrar todo en un JOptionPane
        JOptionPane.showMessageDialog(this, sb.toString(), "Videollamadas Registradas", JOptionPane.INFORMATION_MESSAGE);

    }//GEN-LAST:event_btnViewVideoCallsActionPerformed

    private boolean validateForm() {
       
        String name = txtCustomerName.getText();
        String hour = ffVideoCallHour.getText();
        Date date = ffVideoCallDate.getDate();

        if (!validateName(name)) {
            JOptionPane.showMessageDialog(this, "Nombre inválido");
            return false;
        }

        if (!validateHour(hour)) {
            JOptionPane.showMessageDialog(this, "Hora inválida (use HH:mm)");
            return false;
        }

        if (!validateDate(date)) {
            JOptionPane.showMessageDialog(this, "Fecha inválida");
            return false;
        }

        int option = JOptionPane.showConfirmDialog(
            this,
            "¿Está seguro de que desea guardar?",
            "Confirmar guardado",
            JOptionPane.YES_NO_CANCEL_OPTION,
            JOptionPane.QUESTION_MESSAGE
        );

        if (option != JOptionPane.YES_OPTION) {
            return false; // canceló o no quiere guardar
        }

        return true;
    }
    
    private VideoCall readForm() {
        
        String name = txtCustomerName.getText();
        String hour = ffVideoCallHour.getText();
        Date date = ffVideoCallDate.getDate();
        String medium = cbMedium.getSelectedItem().toString();
        String note = txtNote.getText();

        VideoCall call = new VideoCall();
        call.setCustomerName(name);
        call.setVideoCallHour(hour);
        call.setVideoCallDate(formatDate(date));
        call.setMedium(medium);
        call.setNote(note);

        return call;
    }
    
    private boolean validateName(String name) {
        if (name == null || name.trim().isEmpty()) {
            System.out.println("El nombre está vacío");
            return false;
        }

        if (!name.matches("[a-zA-Z ]+")) {
            System.out.println("El nombre solo debe contener letras");
            return false;
        }

        return true;
    }
    
    private boolean validateDate(Date date) {
        if (date == null) {
            System.out.println("La fecha está vacía");
            return false;
        }

        // Obtener solo la fecha de hoy sin horas
        java.util.Calendar cal = java.util.Calendar.getInstance();
        cal.set(java.util.Calendar.HOUR_OF_DAY, 0);
        cal.set(java.util.Calendar.MINUTE, 0);
        cal.set(java.util.Calendar.SECOND, 0);
        cal.set(java.util.Calendar.MILLISECOND, 0);
        Date today = cal.getTime();

        // Validar que la fecha no sea pasada
        if (date.before(today)) {
            System.out.println("La fecha es pasada");
            return false;
        }

        return true;
    }

    private boolean validateHour(String hour) {
        if (hour == null || hour.trim().isEmpty()) {
            System.out.println("La hora está vacía");
            return false;
        }

        // Validar formato HH:mm
        if (!hour.matches("^([01]\\d|2[0-3]):[0-5]\\d$")) {
            System.out.println("La hora no tiene un formato correcto (HH:mm)");
            return false;
        }

        return true;
    }
    
    private String formatDate(Date date) {
        java.text.SimpleDateFormat sdf = new java.text.SimpleDateFormat("dd/MM/yyyy");
        return sdf.format(date);
    }
    private void clearForm() {
        txtCustomerName.setText("");
        ffVideoCallHour.setText("");
        ffVideoCallDate.setDate(null);
        cbMedium.setSelectedIndex(0);
        txtNote.setText("");
    }
    
