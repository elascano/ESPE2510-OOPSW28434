    private void txtAgeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtAgeActionPerformed
        Date fechaNacimiento = jDateChooser1.getDate();

        if (fechaNacimiento != null) {
            // Convertir Date a LocalDate
            Instant instant = fechaNacimiento.toInstant();
            LocalDate birthDate = instant.atZone(ZoneId.systemDefault()).toLocalDate();

            // Calcular la edad
            int edad = Period.between(birthDate, LocalDate.now()).getYears();

            // Mostrar la edad en el JTextField
            txtAge.setText(String.valueOf(edad));
        } else {
            JOptionPane.showMessageDialog(this, "Seleccione una fecha válida.");
        }
    }//GEN-LAST:event_txtAgeActionPerformed

