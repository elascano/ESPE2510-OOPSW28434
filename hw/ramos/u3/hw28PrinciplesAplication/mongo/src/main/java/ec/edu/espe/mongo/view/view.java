    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        int id = Integer.parseInt(txtId.getText());
        String name = txtName.getText();
        float price = Float.parseFloat(txtPrice.getText());

        Store store = new Store(id, name, price, 0);
        mongoCrud.create(store);

        txtPriceIva.setText(String.valueOf(store.calculatePriceIva()));

        JOptionPane.showMessageDialog(this, "Store saved");
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed

        int id = Integer.parseInt(txtId.getText());
        mongoCrud.delete(id);

        txtId.setText("");
        txtName.setText("");
        txtPrice.setText("");
        txtPriceIva.setText("");

        JOptionPane.showMessageDialog(this, "Store deleted");
    }//GEN-LAST:event_btnDeleteActionPerformed

