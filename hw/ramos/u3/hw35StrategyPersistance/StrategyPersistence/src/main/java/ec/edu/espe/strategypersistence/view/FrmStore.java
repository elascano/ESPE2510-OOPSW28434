    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed

        try {
            int id = Integer.parseInt(txtId.getText());
            String name = txtName.getText();
            float price = Float.parseFloat(txtPrice.getText());
            String category = txtCategory.getText();

            Store nuevo = new Store(id, name, price, category);
            manager.create(nuevo);

            JOptionPane.showMessageDialog(this, "Products saved");
        } catch (NumberFormatException ex) {
            JOptionPane.showMessageDialog(this, "Error");
        }
    }//GEN-LAST:event_btnCreateActionPerformed

    private void btnLoadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnLoadActionPerformed

        List<Store> lista = manager.loadAll();
        DefaultTableModel modelo = (DefaultTableModel) tblStore.getModel();
        modelo.setRowCount(0);
        for (Store s : lista) {
            Object[] fila = {s.getId(), s.getName(), s.getPrice(), s.getCategory()};
            modelo.addRow(fila);
        }
    }//GEN-LAST:event_btnLoadActionPerformed

    private void btnFindActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnFindActionPerformed

        int idBuscar = Integer.parseInt(txtId.getText());
        Store encontrado = manager.find(idBuscar);

        if (encontrado != null) {
            txtName.setText(encontrado.getName());
            txtPrice.setText(String.valueOf(encontrado.getPrice()));
            txtCategory.setText(encontrado.getCategory());
        } else {
            JOptionPane.showMessageDialog(this, "The product was not found.");
        }
    }//GEN-LAST:event_btnFindActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed

        int id = Integer.parseInt(txtId.getText());
        Store editado = new Store(id, txtName.getText(), Float.parseFloat(txtPrice.getText()), txtCategory.getText());

        manager.update(id, editado);
        JOptionPane.showMessageDialog(this, "updated product");
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        int idEliminar = Integer.parseInt(txtId.getText());
        int confirmar = JOptionPane.showConfirmDialog(this, "I'm sure you want to delete?");

        if (confirmar == JOptionPane.YES_OPTION) {
            manager.delete(idEliminar);
            JOptionPane.showMessageDialog(this, "product removed");
        }
    }//GEN-LAST:event_btnDeleteActionPerformed

    private void cmbPersistenceActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_cmbPersistenceActionPerformed
        String op = cmbPersistence.getSelectedItem().toString();

        if (op.equals("MongoDB")) {
            manager.setStrategy(new MongoStrategy());
        } else if (op.equals("JSON")) {
            manager.setStrategy(new GsonStrategy());
        } else if (op.equals("CSV")) {
            manager.setStrategy(new CsvStrategy());
        }
    }//GEN-LAST:event_cmbPersistenceActionPerformed

