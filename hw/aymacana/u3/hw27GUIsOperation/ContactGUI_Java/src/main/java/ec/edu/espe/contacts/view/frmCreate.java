    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
         try {
        // 1. Obtener datos de los campos
        String contactName = txtName.getText().trim();
        String phone = txtPhone.getText().trim();
        String email = txtEmail.getText().trim();
        String address = txtAddress.getText().trim();
        
        // 2. Mostrar confirmación
        int confirm = JOptionPane.showConfirmDialog(
            this,
            "¿Está seguro de agregar este contacto?\n\n" +
            "Nombre: " + contactName + "\n" +
            "Telefono: " + phone + "\n" +
            "Email: " + email + "\n" +
            "Direccion: " + address,
            "Confirmar",
            JOptionPane.YES_NO_OPTION
        );
        
        if (confirm != JOptionPane.YES_OPTION) {
            return; // Cancelar si el usuario dice NO
        }
        
        // 3. Convertir número de jugadores
        int numberAddress = Integer.parseInt(address);
        
        // 4. Crear instancia del Controller
        Controller controller = new Controller();
        
        // 5. Llamar al método addTeam() del Controller
        int newId = controller.addTeam(contactName, phone, email, ALLBITS);
        
        // 6. Mostrar resultado
        if (newId > 0) {
            JOptionPane.showMessageDialog(
                this,
                "✅ Equipo agregado exitosamente!\nID asignado: " + newId,
                "Éxito",
                JOptionPane.INFORMATION_MESSAGE
            );
            
            // 7. Limpiar campos después de agregar
            txtName.setText("");
            txtPhone.setText("");
            txtEmail.setText("");
            txtAddress.setText("");
            txtName.requestFocus(); // Poner foco en el primer campo
            
        } else {
            JOptionPane.showMessageDialog(
                this,
                "❌ Error al guardar",
                "Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
        
    } catch (NumberFormatException e) {
        // Si el usuario no ingresa un número válido
        JOptionPane.showMessageDialog(
            this,
            "❌ Error: Ingrese un número válido",
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
        txtAddress.requestFocus();
        
    } catch (Exception e) {
        // Para cualquier otro error
        JOptionPane.showMessageDialog(
            this,
            "❌ Error: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
        }
    }//GEN-LAST:event_jButton1ActionPerformed

