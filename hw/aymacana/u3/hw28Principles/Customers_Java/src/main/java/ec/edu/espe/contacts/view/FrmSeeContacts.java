    private void configureTable() {
        DefaultTableModel model = new DefaultTableModel() {
            @Override
            public Class<?> getColumnClass(int columnIndex) {
                return String.class;
            }
            
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        
        String[] columnNames = {
            "ID", 
            "Full Name", 
            "Email", 
            "Type", 
            "Discount", 
            "Total Sale", 
            "Final Price", 
            "Savings"
        };
        
        model.setColumnIdentifiers(columnNames);
        tblContacts.setModel(model);
        
        tblContacts.setRowSorter(new TableRowSorter<>(model));
        
        if (tblContacts.getColumnModel().getColumnCount() >= 8) {
            tblContacts.getColumnModel().getColumn(0).setPreferredWidth(50);    
            tblContacts.getColumnModel().getColumn(1).setPreferredWidth(150);   
            tblContacts.getColumnModel().getColumn(2).setPreferredWidth(200);   
            tblContacts.getColumnModel().getColumn(3).setPreferredWidth(80);    
            tblContacts.getColumnModel().getColumn(4).setPreferredWidth(80);    
            tblContacts.getColumnModel().getColumn(5).setPreferredWidth(100);   
            tblContacts.getColumnModel().getColumn(6).setPreferredWidth(100);   
            tblContacts.getColumnModel().getColumn(7).setPreferredWidth(100);   
        }
    }
    
    private void loadContacts() {
        try {
            List<Contact> contacts = contactController.getAllContacts();
            
            DefaultTableModel model = (DefaultTableModel) tblContacts.getModel();
            
            model.setRowCount(0);
            
            for (Contact contact : contacts) {
                Object[] row = {
                    String.valueOf(contact.getId()),
                    contact.getFullName(),
                    contact.getEmail(),
                    contact.getType().getDisplayName(),
                    contact.getDiscount() + "%",
                    CurrencyFormatter.format(contact.getTotalSale()),
                    CurrencyFormatter.format(contact.calculateFinalPrice()),
                    CurrencyFormatter.format(contact.getSavings())
                };
                model.addRow(row);
            }
            
            
            System.out.println("Loaded " + contacts.size() + " contacts");
            
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Error loading contacts: " + e.getMessage(),
                "Connection Error",
                JOptionPane.ERROR_MESSAGE);
            System.err.println("Error: " + e.getMessage());
        }
    }
    

