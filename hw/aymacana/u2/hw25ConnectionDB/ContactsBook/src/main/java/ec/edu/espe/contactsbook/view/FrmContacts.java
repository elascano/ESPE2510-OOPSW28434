    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        if (txtFirstName.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Please enter First Name",
                    "Required Field",
                    JOptionPane.WARNING_MESSAGE);
            txtFirstName.requestFocus();
            return;
        }

        if (txtLastName.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Please enter Last Name",
                    "Required Field",
                    JOptionPane.WARNING_MESSAGE);
            txtLastName.requestFocus();
            return;
        }

        int age = 0;
        String ageText = txtAge.getText().trim();
        if (!ageText.isEmpty()) {
            try {
                age = Integer.parseInt(ageText);
                if (age < 0 || age > 150) {
                    JOptionPane.showMessageDialog(this,
                            "Age must be between 0 and 150",
                            "Invalid Age",
                            JOptionPane.WARNING_MESSAGE);
                    txtAge.requestFocus();
                    return;
                }
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this,
                        "Age must be a valid number",
                        "Invalid Age",
                        JOptionPane.WARNING_MESSAGE);
                txtAge.requestFocus();
                return;
            }
        }

        Date birthDate = null;
        if (jDateChooser1.getDate() == null) {
            JOptionPane.showMessageDialog(this,
                    "Please select a birth date",
                    "Required Field",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }
        birthDate = jDateChooser1.getDate();

        String typeOfContact = "";
        if (cmbType.getSelectedItem() != null) {
            typeOfContact = cmbType.getSelectedItem().toString();
        } else {
            JOptionPane.showMessageDialog(this,
                    "Please select a contact type",
                    "Required Field",
                    JOptionPane.WARNING_MESSAGE);
            cmbType.requestFocus();
            return;
        }

        String sex = "";
        if (radSexMale.isSelected()) {
            sex = "Male";
        } else if (radSexFemale.isSelected()) {
            sex = "Female";
        } else {
            JOptionPane.showMessageDialog(this,
                    "Please select gender",
                    "Required Field",
                    JOptionPane.WARNING_MESSAGE);
            return;
        }

        ArrayList<String> hobbies = new ArrayList<>();

        if (cbxPlaySoccer.isSelected()) {
            hobbies.add("Play Soccer");
        }
        if (cbxDj.isSelected()) {
            hobbies.add("DJ");
        }
        if (cbxRead.isSelected()) {
            hobbies.add("Read");
        }
        if (cbxCook.isSelected()) {
            hobbies.add("Cook");
        }
        if (Swimn.isSelected()) {
            hobbies.add("Swim");
        }
        if (cbxSing.isSelected()) {
            hobbies.add("Sing");
        }
        if (cbxPlayInstrument.isSelected()) {
            hobbies.add("Play an Instrument");
        }

        if (cbxOther.isSelected()) {
            String otherHobby = txtOtherHobbies.getText().trim();
            if (!otherHobby.isEmpty()) {
                hobbies.add(otherHobby);
            } else {
                JOptionPane.showMessageDialog(this,
                        "Please enter the other hobby",
                        "Required Field",
                        JOptionPane.WARNING_MESSAGE);
                txtOtherHobbies.requestFocus();
                return;
            }
        }

        String comments = txeComments.getText().trim();

        try {
            SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
            String birthDateStr = sdf.format(birthDate);

            Contact contact = new Contact(
                    0,
                    txtFirstName.getText().trim(),
                    txtLastName.getText().trim(),
                    age,
                    typeOfContact,
                    sex,
                    hobbies,
                    comments
            );

            ContacsBookController controller = new ContacsBookController();
            boolean saved = controller.saveContact(contact, birthDateStr);

            if (saved) {
                JOptionPane.showMessageDialog(this,
                        "Contact saved successfully in MongoDB",
                        "Success",
                        JOptionPane.INFORMATION_MESSAGE);

                clearFormFields();
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Error saving contact: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }

    private void clearFormFields() {
        txtFirstName.setText("");
        txtLastName.setText("");
        txtAge.setText("");
        txtOtherHobbies.setText("");
        txeComments.setText("");

        cmbType.setSelectedIndex(0);

        buttonGroupSex.clearSelection();
        radSexMale.setSelected(true);

        jDateChooser1.setDate(new Date());

        cbxPlaySoccer.setSelected(false);
        cbxDj.setSelected(false);
        cbxRead.setSelected(false);
        cbxCook.setSelected(false);
        Swimn.setSelected(false);
        cbxSing.setSelected(false);
        cbxPlayInstrument.setSelected(false);
        cbxOther.setSelected(false);

        txtFirstName.requestFocus();
    }//GEN-LAST:event_btnSaveActionPerformed

