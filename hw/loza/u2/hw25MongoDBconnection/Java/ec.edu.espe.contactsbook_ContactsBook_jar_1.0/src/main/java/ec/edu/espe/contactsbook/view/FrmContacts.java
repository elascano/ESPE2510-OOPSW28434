    private void emptyFields() {
        txtFirstName.setText("");
        txtLastName.setText("");
        ftdBirthDate.setText("");
        cmbType.setSelectedIndex(0);
        radSexFemale.setSelected(true);
        lstHobbies.clearSelection();
        txaComments.setText("");
    }

    private int calculateAge(String birthDate) {
        try {
            DateTimeFormatter fmt = DateTimeFormatter.ofPattern("M/d/yy");
            LocalDate date = LocalDate.parse(birthDate, fmt);
            return Period.between(date, LocalDate.now()).getYears();
        } catch (Exception e) {
            return 0;
        }
    }

    private void readValues() {
        String firstName = txtFirstName.getText();
        String lastName = txtLastName.getText();
        String birthDate = ftdBirthDate.getText();

        int age = calculateAge(birthDate);
        txtBirthdateCalculate.setText(String.valueOf(age));

        String typeOfContact = cmbType.getSelectedItem().toString();

        String sex = radSexMale.isSelected() ? "Male" : "Female";

        ArrayList<String> hobbies = new ArrayList<>();
        hobbies.add(lstHobbies.getSelectedValue());

        String comments = txaComments.getText();

        // CONSTRUCTOR CORRECTO !!!
        contact = new Contact(firstName, lastName, age, typeOfContact, sex, hobbies, comments);
    }

    private void saveContactToJson(Contact contact) {
        try {
            // Se crea una cadena JSON manualmente
            StringBuilder json = new StringBuilder();
            json.append("{\n");
            json.append("  \"id\": ").append(contact.getId()).append(",\n");
            json.append("  \"firstName\": \"").append(contact.getFirstName()).append("\",\n");
            json.append("  \"lastName\": \"").append(contact.getLastName()).append("\",\n");
            json.append("  \"age\": ").append(contact.getAge()).append(",\n");
            json.append("  \"typeOfContact\": \"").append(contact.getTypeOfContact()).append("\",\n");
            json.append("  \"sex\": \"").append(contact.getSex()).append("\",\n");

            // Hobbies en JSON
            json.append("  \"hobbies\": [");
            for (int i = 0; i < contact.getHobbies().size(); i++) {
                json.append("\"").append(contact.getHobbies().get(i)).append("\"");
                if (i < contact.getHobbies().size() - 1) {
                    json.append(", ");
                }
            }
            json.append("],\n");

            json.append("  \"comments\": \"").append(contact.getComments()).append("\"\n");
            json.append("}");
            json.append("  \"id\": ").append(contact.getId()).append(",\n");
            json.append("  \"age\": ").append(contact.getAge()).append(",\n");

            // Guardado del archivo JSON
            java.io.FileWriter file = new java.io.FileWriter("contacts.json", true);
            file.write(json.toString() + "\n");
            file.close();

            JOptionPane.showMessageDialog(rootPane, "Contacto guardado en JSON (contacts.json)");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error al guardar en JSON: " + e.getMessage());
        }
    }

    private void saveContactToMongo(Contact contact) {
        try {
            // Obtenemos la base de datos
            MongoDatabase database = MongoDBUtil.getDatabase();

            // Obtenemos la colección
            MongoCollection<Document> collection = database.getCollection("contacts");

            Document doc = new Document()
                    .append("id", contact.getId())
                    .append("firstName", contact.getFirstName())
                    .append("lastName", contact.getLastName())
                    .append("age", contact.getAge())
                    .append("typeOfContact", contact.getTypeOfContact())
                    .append("sex", contact.getSex())
                    .append("comments", contact.getComments());

            doc.append("hobbies", contact.getHobbies());

            collection.insertOne(doc);

            JOptionPane.showMessageDialog(rootPane, "Contacto guardado en MongoDB Atlas");

        } catch (Exception e) {
            JOptionPane.showMessageDialog(rootPane, "Error al guardar en MongoDB: " + e.getMessage());
        }
    }

