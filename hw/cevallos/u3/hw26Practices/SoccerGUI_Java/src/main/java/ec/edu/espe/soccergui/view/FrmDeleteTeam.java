    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        try {
            // 1. Obtener ID del campo de texto
            String idStr = txtTeamId.getText().trim();

            // 2. Validar que no esté vacío
            if (idStr.isEmpty()) {
                JOptionPane.showMessageDialog(
                        this,
                        "❌ Por favor ingrese un ID",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
                txtTeamId.requestFocus();
                return;
            }

            // 3. Convertir ID a número
            int teamId = Integer.parseInt(idStr);

            // 4. Guardar el ID para usarlo después en Delete
            currentTeamId = teamId;

            // 5. Crear instancia del Controller
            controller = new SoccerTeamController();

            // 6. Buscar equipo usando getTeam()
            SoccerTeam team = controller.getTeam(teamId);

            // 7. Mostrar información en el Text Area
            if (team != null) {
                // Formatear la información del equipo
                String teamInfo = formatTeamInfo(team);
                txtAreaTeamInfo.setText(teamInfo);

                // Habilitar botón Delete
                btnDelete.setEnabled(true);

            } else {
                txtAreaTeamInfo.setText("❌ No se encontró equipo con ID: " + teamId);
                btnDelete.setEnabled(false);
            }

        } catch (NumberFormatException e) {
            // Si el usuario no ingresa un número válido
            JOptionPane.showMessageDialog(
                    this,
                    "❌ Error: Ingrese un ID válido (número)",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            txtAreaTeamInfo.setText("❌ ID inválido. Debe ser un número.");
            btnDelete.setEnabled(false);
            txtTeamId.requestFocus();

        } catch (Exception e) {
            // Para cualquier otro error
            JOptionPane.showMessageDialog(
                    this,
                    "❌ Error del sistema: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            txtAreaTeamInfo.setText("❌ Error: " + e.getMessage());
            btnDelete.setEnabled(false);
        }
    }

    // Método auxiliar para formatear la información del equipo
    private String formatTeamInfo(SoccerTeam team) {
        // Usar el arbitraje ya calculado en la clase SoccerTeam
        double arbitrationPerPlayer = team.getArbitration();
        double totalArbitration = arbitrationPerPlayer * team.getNumberOfPlayers();

        return String.format(
                "⚠️ EQUIPO ENCONTRADO PARA ELIMINAR\n\n"
                + "ID: %d\n"
                + "Nombre del equipo: %s\n"
                + "Nombre del entrenador: %s\n"
                + "Ciudad/Barrio: %s\n"
                + "Número de jugadores: %d\n"
                + "Arbitraje por jugador: $%.2f\n"
                + "Costo total de arbitraje: $%.2f\n\n",
                team.getId(),
                team.getTeamName(),
                team.getCoachName(),
                team.getNeighborhoodCity(),
                team.getNumberOfPlayers(),
                arbitrationPerPlayer,
                totalArbitration
        );
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        try {
            // 1. Verificar que se haya buscado un equipo primero
            if (currentTeamId == 0) {
                JOptionPane.showMessageDialog(
                        this,
                        "❌ Por favor busque un equipo primero",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
                return;
            }

            // 2. Mostrar confirmación con los datos del equipo
            SoccerTeam team = controller.getTeam(currentTeamId);

            if (team == null) {
                JOptionPane.showMessageDialog(
                        this,
                        "❌ El equipo ya no existe",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
                return;
            }

            int confirm = JOptionPane.showConfirmDialog(
                    this,
                    "⚠️ ¿ESTÁ SEGURO DE ELIMINAR ESTE EQUIPO?\n\n"
                    + "ID: " + team.getId() + "\n"
                    + "Nombre: " + team.getTeamName() + "\n"
                    + "Entrenador: " + team.getCoachName() + "\n"
                    + "Ciudad: " + team.getNeighborhoodCity() + "\n"
                    + "Jugadores: " + team.getNumberOfPlayers() + "\n\n"
                    + "Esta acción NO se puede deshacer.",
                    "Confirmar eliminación",
                    JOptionPane.YES_NO_OPTION,
                    JOptionPane.WARNING_MESSAGE
            );

            if (confirm != JOptionPane.YES_OPTION) {
                txtAreaTeamInfo.setText("❌ Eliminación cancelada por el usuario");
                return; // Cancelar si el usuario dice NO
            }

            // 3. Llamar al método deleteTeam() del Controller
            boolean success = controller.deleteTeam(currentTeamId);

            // 4. Mostrar resultado
            if (success) {
                JOptionPane.showMessageDialog(
                        this,
                        "✅ Equipo eliminado exitosamente!",
                        "Éxito",
                        JOptionPane.INFORMATION_MESSAGE
                );

                // Limpiar campos después de eliminar
                clearFields();

            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "❌ Error al eliminar el equipo",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
            }

        } catch (Exception e) {
            // Para cualquier error
            JOptionPane.showMessageDialog(
                    this,
                    "❌ Error del sistema: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            txtAreaTeamInfo.setText("❌ Error: " + e.getMessage());
        }
    }

    // Método para limpiar campos
    private void clearFields() {
        txtTeamId.setText("");
        txtAreaTeamInfo.setText("");
        btnDelete.setEnabled(false);


    }//GEN-LAST:event_btnDeleteActionPerformed

