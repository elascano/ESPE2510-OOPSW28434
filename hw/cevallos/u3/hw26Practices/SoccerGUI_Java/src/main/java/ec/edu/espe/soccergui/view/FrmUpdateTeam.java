    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        try {
            // 1. Obtener ID del campo de texto
            String idStr = txtTeamId.getText().trim();

            // 2. Validar que no esté vacío
            if (idStr.isEmpty()) {
                JOptionPane.showMessageDialog(
                        this,
                        "❌ Por favor ingrese un ID",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
                txtTeamId.requestFocus();
                return;
            }

            // 3. Convertir ID a número
            int teamId = Integer.parseInt(idStr);

            // 4. Guardar el ID para usarlo después en Update
            currentTeamId = teamId;

            // 5. Crear instancia del Controller
            controller = new SoccerTeamController();

            // 6. Buscar equipo usando getTeam()
            SoccerTeam team = controller.getTeam(teamId);

            // 7. Si encuentra el equipo, llenar los campos
            if (team != null) {
                // Llenar los campos con los datos del equipo
                txtTeamName.setText(team.getTeamName());
                txtCoachName.setText(team.getCoachName());
                txtCity.setText(team.getNeighborhoodCity());
                txtNumberPlayers.setText(String.valueOf(team.getNumberOfPlayers()));

                // Habilitar los campos para edición
                enableFields(true);

                // Mostrar mensaje de éxito
                JOptionPane.showMessageDialog(
                        this,
                        "✅ Equipo encontrado. Puede modificar los campos.",
                        "Éxito",
                        JOptionPane.INFORMATION_MESSAGE
                );

                // Poner foco en el primer campo a modificar
                txtTeamName.requestFocus();

            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "❌ No se encontró equipo con ID: " + teamId,
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
                clearFields();
                enableFields(false);
            }

        } catch (NumberFormatException e) {
            // Si el usuario no ingresa un número válido
            JOptionPane.showMessageDialog(
                    this,
                    "❌ Error: Ingrese un ID válido (número)",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            clearFields();
            enableFields(false);
            txtTeamId.requestFocus();

        } catch (Exception e) {
            // Para cualquier otro error
            JOptionPane.showMessageDialog(
                    this,
                    "❌ Error del sistema: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            clearFields();
            enableFields(false);
        }
    }

// Método para habilitar/deshabilitar campos
    private void enableFields(boolean enabled) {
        txtTeamName.setEnabled(enabled);
        txtCoachName.setEnabled(enabled);
        txtCity.setEnabled(enabled);
        txtNumberPlayers.setEnabled(enabled);
        btnUpdate.setEnabled(enabled);
    }

// Método para limpiar campos
    private void clearFields() {
        txtTeamName.setText("");
        txtCoachName.setText("");
        txtCity.setText("");
        txtNumberPlayers.setText("");
        currentTeamId = 0;

    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        try {
            // 1. Verificar que se haya buscado un equipo primero
            if (currentTeamId == 0) {
                JOptionPane.showMessageDialog(
                        this,
                        "❌ Por favor busque un equipo primero",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
                return;
            }

            // 2. Obtener los nuevos valores de los campos
            String newTeamName = txtTeamName.getText().trim();
            String newCoachName = txtCoachName.getText().trim();
            String newCity = txtCity.getText().trim();
            String newPlayersStr = txtNumberPlayers.getText().trim();

            // 3. Validar que los campos no estén vacíos
            if (newTeamName.isEmpty() || newCoachName.isEmpty()
                    || newCity.isEmpty() || newPlayersStr.isEmpty()) {
                JOptionPane.showMessageDialog(
                        this,
                        "❌ Todos los campos son requeridos",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
                return;
            }

            // 4. Convertir número de jugadores
            int newNumberOfPlayers = Integer.parseInt(newPlayersStr);

            // 5. Mostrar confirmación con los cambios
            int confirm = JOptionPane.showConfirmDialog(
                    this,
                    "¿Está seguro de actualizar este equipo?\n\n"
                    + "ID: " + currentTeamId + "\n"
                    + "Nuevo nombre: " + newTeamName + "\n"
                    + "Nuevo entrenador: " + newCoachName + "\n"
                    + "Nueva ciudad: " + newCity + "\n"
                    + "Nuevo número de jugadores: " + newNumberOfPlayers,
                    "Confirmar actualización",
                    JOptionPane.YES_NO_OPTION,
                    JOptionPane.QUESTION_MESSAGE
            );

            if (confirm != JOptionPane.YES_OPTION) {
                return; // Cancelar si el usuario dice NO
            }

            // 6. Llamar al método updateTeam() del Controller
            boolean success = controller.updateTeam(
                    currentTeamId,
                    newTeamName,
                    newCoachName,
                    newCity,
                    newNumberOfPlayers
            );

            // 7. Mostrar resultado
            if (success) {
                JOptionPane.showMessageDialog(
                        this,
                        "✅ Equipo actualizado exitosamente!",
                        "Éxito",
                        JOptionPane.INFORMATION_MESSAGE
                );

                // Limpiar campos después de actualizar
                clearFields();
                txtTeamId.setText("");
                enableFields(false);

            } else {
                JOptionPane.showMessageDialog(
                        this,
                        "❌ Error al actualizar el equipo",
                        "Error",
                        JOptionPane.ERROR_MESSAGE
                );
            }

        } catch (NumberFormatException e) {
            // Si el usuario no ingresa un número válido
            JOptionPane.showMessageDialog(
                    this,
                    "❌ Error: Ingrese un número válido de jugadores",
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
            txtNumberPlayers.requestFocus();

        } catch (Exception e) {
            // Para cualquier otro error
            JOptionPane.showMessageDialog(
                    this,
                    "❌ Error del sistema: " + e.getMessage(),
                    "Error",
                    JOptionPane.ERROR_MESSAGE
            );
        }
    }//GEN-LAST:event_btnUpdateActionPerformed

