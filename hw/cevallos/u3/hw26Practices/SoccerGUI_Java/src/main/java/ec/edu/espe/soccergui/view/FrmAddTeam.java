    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        try {
        // 1. Obtener datos de los campos
        String teamName = txtTeamName.getText().trim();
        String coachName = txtCoachName.getText().trim();
        String city = txtCity.getText().trim();
        String playersStr = txtNumberPlayers.getText().trim();
        
        // 2. Mostrar confirmación
        int confirm = JOptionPane.showConfirmDialog(
            this,
            "¿Está seguro de agregar este equipo?\n\n" +
            "Equipo: " + teamName + "\n" +
            "Entrenador: " + coachName + "\n" +
            "Ciudad: " + city + "\n" +
            "Jugadores: " + playersStr,
            "Confirmar",
            JOptionPane.YES_NO_OPTION
        );
        
        if (confirm != JOptionPane.YES_OPTION) {
            return; // Cancelar si el usuario dice NO
        }
        
        // 3. Convertir número de jugadores
        int numberOfPlayers = Integer.parseInt(playersStr);
        
        // 4. Crear instancia del Controller
        SoccerTeamController controller = new SoccerTeamController();
        
        // 5. Llamar al método addTeam() del Controller
        int newId = controller.addTeam(teamName, coachName, city, numberOfPlayers);
        
        // 6. Mostrar resultado
        if (newId > 0) {
            JOptionPane.showMessageDialog(
                this,
                "✅ Equipo agregado exitosamente!\nID asignado: " + newId,
                "Éxito",
                JOptionPane.INFORMATION_MESSAGE
            );
            
            // 7. Limpiar campos después de agregar
            txtTeamName.setText("");
            txtCoachName.setText("");
            txtCity.setText("");
            txtNumberPlayers.setText("");
            txtTeamName.requestFocus(); // Poner foco en el primer campo
            
        } else {
            JOptionPane.showMessageDialog(
                this,
                "❌ Error al guardar el equipo",
                "Error",
                JOptionPane.ERROR_MESSAGE
            );
        }
        
    } catch (NumberFormatException e) {
        // Si el usuario no ingresa un número válido
        JOptionPane.showMessageDialog(
            this,
            "❌ Error: Ingrese un número válido de jugadores",
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
        txtNumberPlayers.requestFocus();
        
    } catch (Exception e) {
        // Para cualquier otro error
        JOptionPane.showMessageDialog(
            this,
            "❌ Error: " + e.getMessage(),
            "Error",
            JOptionPane.ERROR_MESSAGE
        );
    }
    }//GEN-LAST:event_btnAddActionPerformed

