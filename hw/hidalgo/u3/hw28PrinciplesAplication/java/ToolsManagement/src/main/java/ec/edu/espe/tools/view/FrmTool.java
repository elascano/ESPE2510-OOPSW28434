    @Override
    public void refreshTable(java.util.List<ec.edu.espe.tools.model.Tool> tools) {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) tabSculptures.getModel();
        model.setRowCount(0);

        for (ec.edu.espe.tools.model.Tool t : tools) {
            String matString = String.join(", ", t.getMaterials());

            model.addRow(new Object[]{
                t.getId(),
                t.getName(),
                matString,
                t.getPrice(),
                t.getPriceWithIva()
            });
        }
    }

