    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed
        controller.createProduct(txtId.getText(), txtName.getText(), Double.parseDouble(txtPrice.getText()));
        loadTable();
    }//GEN-LAST:event_btnCreateActionPerformed

    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        Product p = controller.findProduct(txtId.getText());
        if (p != null) {
            txtName.setText(p.getName());
            txtPrice.setText(String.valueOf(p.getBasePrice()));
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Product Not Found");
        }
    }//GEN-LAST:event_btnSearchActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
        controller.updateProduct(txtId.getText(), txtName.getText(), Double.parseDouble(txtPrice.getText()));
        loadTable();
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
        controller.deleteProduct(txtId.getText());
        loadTable();

        txtId.setText("");
        txtName.setText("");
        txtPrice.setText("");
    }//GEN-LAST:event_btnDeleteActionPerformed

