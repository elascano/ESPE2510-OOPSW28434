    private void loadTable() {
        DefaultTableModel model = (DefaultTableModel) tblProducts.getModel();
        model.setRowCount(0);
        List<Product> list = controller.getAllProducts();
        for (Product p : list) {
            model.addRow(new Object[]{p.getId(), p.getName(), p.getBasePrice(), p.getFinalPrice()});
        }
    }

