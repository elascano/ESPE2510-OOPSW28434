    private void btnSaveProfessorActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveProfessorActionPerformed

        String id = txtId.getText().trim();
        String name = txtFullName.getText().trim();
        String subject = cmbSubject.getSelectedItem().toString();
        String salaryStr = txtSalary.getText().trim();

        String validationError = professorController.validateData(id, name, salaryStr);

        if (validationError != null) {
            JOptionPane.showMessageDialog(this, validationError, "Validation Error", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            double salary = Double.parseDouble(salaryStr);
            Professor newProfessor = new Professor(id, name, subject, salary);

            if (professorController.registerProfessor(newProfessor)) {
                JOptionPane.showMessageDialog(this, "Professor successfully registered in university_db!");
                updateTableData(); 
                clearInputFields(); 
            } else {
                JOptionPane.showMessageDialog(this, "Database Error: Could not save the record.", "Error", JOptionPane.ERROR_MESSAGE);
            }
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Invalid numeric format for salary.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnSaveProfessorActionPerformed

