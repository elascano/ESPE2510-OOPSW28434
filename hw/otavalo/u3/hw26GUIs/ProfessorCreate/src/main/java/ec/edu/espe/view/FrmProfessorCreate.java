    private void updateTableData() {
        List<Professor> professors = professorController.fetchAllProfessors();
        DefaultTableModel model = (DefaultTableModel) tblProfessor.getModel();

        model.setRowCount(0); 

        for (Professor profesor : professors) {
            Object[] row = {
                profesor.getId(),
                profesor.getFullName(),
                profesor.getSubject(),
                String.format("%.2f", profesor.getSalary()),
                String.format("%.2f", profesor.getBonus())
            };
            model.addRow(row);
        }
    }

