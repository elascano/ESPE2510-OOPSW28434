    private void updateTableData() {
        List<Professor> professors = professorController.fetchAllProfessors();
        DefaultTableModel model = (DefaultTableModel) tblProfessor.getModel();
        model.setRowCount(0);

        for (Professor professor : professors) {
            Object[] row = {
                professor.getId(),
                professor.getFullName(),
                professor.getSubject(),
                String.format("%.2f", professor.getSalary()),
                String.format("%.2f", professor.getBonus()) 
            };
            model.addRow(row);
        }
    }

