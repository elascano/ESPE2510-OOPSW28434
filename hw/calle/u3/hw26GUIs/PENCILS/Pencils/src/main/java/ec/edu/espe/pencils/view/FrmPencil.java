private void loadTable() {
    DefaultTableModel model = (DefaultTableModel) tblPencils.getModel();
    model.setRowCount(0); 
    
    List<Pencil> pencils = pencilController.readAll();
    for (Pencil p : pencils) {
        Object[] row = {p.getId(), p.getBrand(), p.getColor(), p.getPrice()};
        model.addRow(row);
    }
}
