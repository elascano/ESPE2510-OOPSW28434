    private void btnSaveActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSaveActionPerformed
        try {
            String id = txtId.getText();
            String brand = txtBrand.getText();
            String color = txtColor.getText();
            double price = Double.parseDouble(txtPrice.getText());

            Pencil pencil = new Pencil(id, brand, color, price);

            pencilController.create(pencil);

            JOptionPane.showMessageDialog(this, "Pencil guardado correctamente en MongoDB");
            clearFields();
            
        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "Error: El precio debe ser un número válido", "Error de entrada", JOptionPane.ERROR_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error  " + e.getMessage());
        }
    }                                       

    private void clearFields() {
        txtId.setText("");
        txtBrand.setText("");
        txtColor.setText("");
        txtPrice.setText("");
    
    }//GEN-LAST:event_btnSaveActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
    String id = txtId.getText();
    if (id.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Por favor seleccione un registro de la tabla");
        return;
    }

    int confirm = JOptionPane.showConfirmDialog(this, "¿Está seguro de eliminar el ID: " + id + "?");
    if (confirm == JOptionPane.YES_OPTION) {
        pencilController.delete(id);
        loadTable();
        clearFields();
        JOptionPane.showMessageDialog(this, "Registro eliminado");
    }

    }//GEN-LAST:event_btnDeleteActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
    try {
        Pencil pencil = new Pencil(
            txtId.getText(), 
            txtBrand.getText(), 
            txtColor.getText(), 
            Double.parseDouble(txtPrice.getText())
        );
        
        pencilController.update(pencil); // Llama al controlador
        loadTable(); // Refresca la tabla para ver el cambio
        JOptionPane.showMessageDialog(this, "Lápiz actualizado con éxito");
        clearFields();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "Error al actualizar: " + e.getMessage());
    }

    }//GEN-LAST:event_btnUpdateActionPerformed

    private void tblPencilsMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblPencilsMouseClicked
    int row = tblPencils.getSelectedRow();
    
    // Validar que la fila seleccionada sea válida
    if (row != -1) {
        // Usamos String.valueOf() que maneja nulos de forma más segura que .toString()
        txtId.setText(String.valueOf(tblPencils.getValueAt(row, 0)));
        txtBrand.setText(String.valueOf(tblPencils.getValueAt(row, 1)));
        txtColor.setText(String.valueOf(tblPencils.getValueAt(row, 2)));
        txtPrice.setText(String.valueOf(tblPencils.getValueAt(row, 3)));
    }

    }//GEN-LAST:event_tblPencilsMouseClicked

