    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        String selectedOption = (String) cbxFile.getSelectedItem();
        
        if (selectedOption == null || selectedOption.equals("Select a format...")) {
            JOptionPane.showMessageDialog(this,
                "Please select a format",
                "Required selection", JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        try {
            if (selectedOption.equals("ALL (All formats)")) {
                loadAllFormats();
            } else {
                loadSingleFormat(selectedOption);
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Error loading data: " + e.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnSearchActionPerformed

