    private void loadSingleFormat(String format) {
        tableModel.setRowCount(0);
        
        controller.setStorageType(format);
        
        List<Customer> customers = controller.getAllCustomers();
        
        if (customers.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                "No clients were found in the format " + format,
                "Sin datos", JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        
        for (Customer customer : customers) {
            Object[] row = {
                customer.getId(),
                customer.getName(),
                customer.getEmail(),
                customer.getPhone()
            };
            tableModel.addRow(row);
        }
        
    }
    
    private void loadAllFormats() {
        tableModel.setRowCount(0);
        
        int totalCustomers = 0;
        
        controller.setStorageType("JSON");
        List<Customer> jsonCustomers = controller.getAllCustomers();
        addCustomersToTable(jsonCustomers, "JSON");
        totalCustomers += jsonCustomers.size();
        
        controller.setStorageType("CSV");
        List<Customer> csvCustomers = controller.getAllCustomers();
        addCustomersToTable(csvCustomers, "CSV");
        totalCustomers += csvCustomers.size();
        
        controller.setStorageType("MongoDB");
        List<Customer> mongoCustomers = controller.getAllCustomers();
        addCustomersToTable(mongoCustomers, "MongoDB");
        totalCustomers += mongoCustomers.size();
        
        if (totalCustomers == 0) {
            JOptionPane.showMessageDialog(this,
                "No customers were found in any format.",
                "Sin datos", JOptionPane.INFORMATION_MESSAGE);
        }
        
    }
    
    private void addCustomersToTable(List<Customer> customers, String source) {
        for (Customer customer : customers) {
            Object[] row = {
                customer.getId(),
                customer.getName(),
                customer.getEmail(),
                customer.getPhone(),
                source  
            };
            tableModel.addRow(row);
        }
    }
