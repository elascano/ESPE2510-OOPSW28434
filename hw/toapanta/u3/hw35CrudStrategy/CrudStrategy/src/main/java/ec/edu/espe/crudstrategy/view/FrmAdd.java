    private void btnAddActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddActionPerformed
        try {
            String name = txtName.getText().trim();
            String email = txtEmail.getText().trim();
            String phone = txtPhone.getText().trim();
            
            if (name.isEmpty() || email.isEmpty() || phone.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                    "Por favor, complete todos los campos",
                    "Campos vacíos", JOptionPane.WARNING_MESSAGE);
                return;
            }
            
            String[] options = {"JSON", "CSV", "MongoDB", "Cancelar"};
            int choice = JOptionPane.showOptionDialog(
                this,
                "¿Dónde desea guardar el cliente?",
                "Seleccionar formato de almacenamiento",
                JOptionPane.DEFAULT_OPTION,
                JOptionPane.QUESTION_MESSAGE,
                null,
                options,
                options[0]
            );
            
            if (choice == 3 || choice == JOptionPane.CLOSED_OPTION) {
                return;
            }
            
            String storageType = options[choice];
            
            int id = IdGenerator.generateUniqueId();
            Customer customer = new Customer(id, name, email, phone);
            
            controller.setStorageType(storageType);
            
            boolean success = controller.addCustomer(customer);
            
            if (success) {
                JOptionPane.showMessageDialog(this,
                    "Cliente agregado exitosamente en " + storageType + "\n" +
                    "ID asignado: " + id,
                    "Éxito", JOptionPane.INFORMATION_MESSAGE);
                clearFields();
            } else {
                JOptionPane.showMessageDialog(this,
                    "Error al agregar cliente en " + storageType,
                    "Error", JOptionPane.ERROR_MESSAGE);
            }
            
        } catch (IllegalArgumentException e) {
            JOptionPane.showMessageDialog(this, e.getMessage(),
                "Errores de Validación", JOptionPane.WARNING_MESSAGE);
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                "Error inesperado: " + e.getMessage(),
                "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnAddActionPerformed

    private void clearFields() {
        txtName.setText("");
        txtEmail.setText("");
        txtPhone.setText("");
        txtName.requestFocus();
    }
    
