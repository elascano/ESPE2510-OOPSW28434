    private void btnSearchActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSearchActionPerformed
        try {
            String idText = txtId.getText().trim();

            if (idText.isEmpty()) {
                JOptionPane.showMessageDialog(this,
                        "Please enter an ID to search",
                        "ID Required", JOptionPane.WARNING_MESSAGE);
                return;
            }

            int id;
            try {
                id = Integer.parseInt(idText);
            } catch (NumberFormatException e) {
                JOptionPane.showMessageDialog(this,
                        "ID must be a valid number",
                        "Invalid ID", JOptionPane.WARNING_MESSAGE);
                return;
            }

            String foundInFormat = null;
            Customer customerFound = null;

            controller.setStorageType("JSON");
            Customer customerInJson = controller.getCustomerById(id);
            if (customerInJson != null) {
                foundInFormat = "JSON";
                customerFound = customerInJson;
            }

            controller.setStorageType("CSV");
            Customer customerInCsv = controller.getCustomerById(id);
            if (customerInCsv != null) {
                foundInFormat = "CSV";
                customerFound = customerInCsv;
            }

            controller.setStorageType("MongoDB");
            Customer customerInMongo = controller.getCustomerById(id);
            if (customerInMongo != null) {
                foundInFormat = "MongoDB";
                customerFound = customerInMongo;
            }

            if (customerFound == null) {
                JOptionPane.showMessageDialog(this,
                        "No customer found with ID " + id,
                        "Customer Not Found", JOptionPane.WARNING_MESSAGE);
                clearFields();
                return;
            }

            StringBuilder message = new StringBuilder();
            message.append("CUSTOMER INFORMATION\n\n");
            message.append("ID: ").append(customerFound.getId()).append("\n");
            message.append("Name: ").append(customerFound.getName()).append("\n");
            message.append("Email: ").append(customerFound.getEmail()).append("\n");
            message.append("Phone: ").append(customerFound.getPhone()).append("\n\n");
            message.append("Storage format: ").append(foundInFormat).append("\n\n");
            message.append("Are you SURE you want to delete this customer?\n");
            message.append("This action CANNOT be undone.");

            int confirm = JOptionPane.showConfirmDialog(this,
                    message.toString(),
                    "CONFIRM DELETION",
                    JOptionPane.YES_NO_OPTION,
                    JOptionPane.WARNING_MESSAGE);

            if (confirm == JOptionPane.YES_OPTION) {
                controller.setStorageType(foundInFormat);
                boolean success = controller.deleteCustomer(id);

                if (success) {
                    JOptionPane.showMessageDialog(this,
                            "Customer successfully deleted from " + foundInFormat + " format",
                            "Deletion Successful", JOptionPane.INFORMATION_MESSAGE);
                    clearFields();
                } else {
                    JOptionPane.showMessageDialog(this,
                            "Error deleting customer",
                            "Deletion Error", JOptionPane.ERROR_MESSAGE);
                }
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this,
                    "Error processing deletion: " + e.getMessage(),
                    "Error", JOptionPane.ERROR_MESSAGE);
            e.printStackTrace();
        }
    }//GEN-LAST:event_btnSearchActionPerformed

