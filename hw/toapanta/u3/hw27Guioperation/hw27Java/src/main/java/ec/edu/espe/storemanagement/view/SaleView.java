    private void btnCreateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCreateActionPerformed
    try {
        String name = txtProduct.getText();
        double price = Double.parseDouble(txtPrice.getText()); 
        int qty = Integer.parseInt(txtQty.getText());
        
        Sale sale = new Sale(name, price, qty);
        
        saleController.create(sale);
        
        
        refreshTable();
        txtProduct.setText("");
        txtPrice.setText("");
        txtQty.setText("");
        
        javax.swing.JOptionPane.showMessageDialog(this, "Success! Product saved in MongoDB.");
        
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Please check the numbers. Remember to use a dot (.) for decimals.");
    }


    }//GEN-LAST:event_btnCreateActionPerformed

    private void btnReadActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReadActionPerformed
    refreshTable();
    JOptionPane.showMessageDialog(this, "Database synchronized with MongoDB.");
    }//GEN-LAST:event_btnReadActionPerformed

    private void btnUpdateActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnUpdateActionPerformed
    if (!selectedProductName.isEmpty()) {
        try {
            Sale updatedSale = new Sale(txtProduct.getText(), 
                                        Double.parseDouble(txtPrice.getText()), 
                                        Integer.parseInt(txtQty.getText()));
            saleController.update(selectedProductName, updatedSale);
            refreshTable();
            javax.swing.JOptionPane.showMessageDialog(this, "Product updated successfully!");
        } catch (Exception e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error: Use dot (.) for decimals.");
        }
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a product from the table.");
    }

        
    }//GEN-LAST:event_btnUpdateActionPerformed

    private void btnDeleteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnDeleteActionPerformed
    if (!selectedProductName.isEmpty()) {
        int confirm = javax.swing.JOptionPane.showConfirmDialog(this, "Are you sure you want to delete " + selectedProductName + "?");
        if (confirm == 0) {
            saleController.delete(selectedProductName);
            refreshTable();
            clearFields();
            javax.swing.JOptionPane.showMessageDialog(this, "Product deleted.");
        }
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Please select a product from the table.");
    }

    }//GEN-LAST:event_btnDeleteActionPerformed

    private void tblSalesMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblSalesMouseClicked
    int row = tblSales.getSelectedRow();
    
    selectedProductName = tblSales.getValueAt(row, 0).toString(); 
    
    txtProduct.setText(tblSales.getValueAt(row, 0).toString());
    txtPrice.setText(tblSales.getValueAt(row, 1).toString());
    txtQty.setText(tblSales.getValueAt(row, 2).toString());
    
    }//GEN-LAST:event_tblSalesMouseClicked

