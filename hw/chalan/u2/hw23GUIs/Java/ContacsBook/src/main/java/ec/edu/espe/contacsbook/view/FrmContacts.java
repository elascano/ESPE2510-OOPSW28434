    private void updateDays() {

    if (cmbYear.getSelectedItem() == null || cmbMonth.getSelectedItem() == null) {
        return; // evita errores si aún no está todo cargado
    }

    cmbDay.removeAllItems();

    int year = Integer.parseInt(cmbYear.getSelectedItem().toString());
    int month = Integer.parseInt(cmbMonth.getSelectedItem().toString());

    int daysInMonth;

    switch (month) {
        case 1: case 3: case 5: case 7: case 8: case 10: case 12:
            daysInMonth = 31;
            break;
        case 4: case 6: case 9: case 11:
            daysInMonth = 30;
            break;
        case 2:
            // Año bisiesto
            if ((year % 4 == 0 && year % 100 != 0) || (year % 400 == 0)) {
                daysInMonth = 29;
            } else {
                daysInMonth = 28;
            }
            break;
        default:
            daysInMonth = 30;
    }

    for (int day = 1; day <= daysInMonth; day++) {
        cmbDay.addItem(String.valueOf(day));
    }
}
    
    private void initCalendar() {

    for (int y = 1975; y <= 2024; y++) {
        cmbYear.addItem(String.valueOf(y));
    }

    for (int m = 1; m <= 12; m++) {
        cmbMonth.addItem(String.valueOf(m));
    }

    updateDays(); // carga los días según mes y año

    // Seleccionamos automáticamente el primer día (o el actual)
    if (cmbDay.getItemCount() > 0) {
        cmbDay.setSelectedIndex(0);
    }
}
    
    private void calculateAge() {
if (cmbYear.getSelectedItem() == null ||
        cmbMonth.getSelectedItem() == null ||
        cmbDay.getSelectedItem() == null) {
        return;
    }

    int year = Integer.parseInt(cmbYear.getSelectedItem().toString());
    int month = Integer.parseInt(cmbMonth.getSelectedItem().toString());
    int day = Integer.parseInt(cmbDay.getSelectedItem().toString());

    LocalDate birthDate = LocalDate.of(year, month, day);
    LocalDate today = LocalDate.now();

    // Cálculo real de la edad
    int age = Period.between(birthDate, today).getYears();

    lblAge.setText(String.valueOf(age));
}

    
