    private void updateFruitData() {
    if (jComboBoxFruitnameAvailable.getSelectedItem() == null) return;

    String fruitName = jComboBoxFruitnameAvailable.getSelectedItem().toString();

    
    double price = controller.getPriceByName(fruitName);
    jPriceUnit.setText("$ " + price);

   
    int stock = controller.getStockByName(fruitName);

   
    SpinnerNumberModel model = new SpinnerNumberModel(
        stock > 0 ? 1 : 0, 
        0,              
        stock,           
        1                 
    );
    jSpinnerStock.setModel(model);
}


    private void loadFruits() {
    DefaultComboBoxModel<String> model = new DefaultComboBoxModel<>();
    for (String name : controller.getFruitNames()) {
        model.addElement(name);
    }
    jComboBoxFruitnameAvailable.setModel(model);
}
private void loadStockTable() {
    String[] columns = {"Name", "Price", "Stock"};
    DefaultTableModel model = new DefaultTableModel(columns, 0);

    for (Fruit fruit : controller.getAllFruits()) {
        Object[] row = {
            fruit.getName(),
            fruit.getPrice(),
            fruit.getStock()
        };
        model.addRow(row);
    }

    jTablestock.setModel(model);
}


