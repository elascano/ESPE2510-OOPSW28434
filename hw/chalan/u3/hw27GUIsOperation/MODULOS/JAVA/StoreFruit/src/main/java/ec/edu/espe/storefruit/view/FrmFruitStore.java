    private void JbtnBuyActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_JbtnBuyActionPerformed
        String fruitName = jComboBoxFruitnameAvailable.getSelectedItem().toString();
    int quantity = (int) jSpinnerStock.getValue();

    double total = controller.buyFruit(fruitName, quantity);

    if (total == -1) {
        JOptionPane.showMessageDialog(this, "Fruit not found");
    } else if (total == -2) {
        JOptionPane.showMessageDialog(this, "Not enough stock");
    } else {
        jTotalPay.setText("$ " + total);
        JOptionPane.showMessageDialog(this, "Purchase successful");
       loadFruits();
loadStockTable();
    }
    }//GEN-LAST:event_JbtnBuyActionPerformed

