    private void jToggleButton1infobycellActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton1infobycellActionPerformed

   int selectedRow = jTable1InfoCellphones.getSelectedRow();

    if (selectedRow == -1) {
        JOptionPane.showMessageDialog(this, "Please select a cellphone from the table");
        return;
    }

    String id = jTable1InfoCellphones.getValueAt(selectedRow, 0).toString();
    String model = jTable1InfoCellphones.getValueAt(selectedRow, 1).toString();
    String price = jTable1InfoCellphones.getValueAt(selectedRow, 2).toString();

    String message =
            "CELLPHONE INFO\n\n" +
            "ID: " + id + "\n" +
            "Model: " + model + "\n" +
            "Price: $" + price;

    JOptionPane.showMessageDialog(this, message, "Cellphone Info", JOptionPane.INFORMATION_MESSAGE);



    }//GEN-LAST:event_jToggleButton1infobycellActionPerformed

    private void jToggleButton1findCellphoneActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jToggleButton1findCellphoneActionPerformed
String id = jTextField1findid.getText();
DefaultTableModel table = (DefaultTableModel) jTable1InfoCellphones.getModel();
table.setRowCount(0);

Cellphone c = controller.findById(id);

if (c != null) {
    table.addRow(new Object[]{
        c.getId(),
        c.getModel(),
        c.getPrice()
    });
} else {
    JOptionPane.showMessageDialog(this, "Cellphone not found");
}

    }//GEN-LAST:event_jToggleButton1findCellphoneActionPerformed

