    private void configureSpinner() {
       
        SpinnerNumberModel model = new SpinnerNumberModel(1, 1, 5, 1);
        jSpinner1and5horurs.setModel(model);
    }

private void loadPhotographersCombo() {
       
        jComboBox1photographerlist.setEnabled(false);
        jComboBox1photographerlist.removeAllItems();
        jComboBox1photographerlist.addItem("Loading...");


        new Thread(new Runnable() {
            @Override
            public void run() {
               
                photographersList = controller.getPhotographers();

                javax.swing.SwingUtilities.invokeLater(new Runnable() {
                    @Override
                    public void run() {
                        jComboBox1photographerlist.removeAllItems();
                        
                        if (photographersList.isEmpty()) {
                            jComboBox1photographerlist.addItem("No photographers found");
                        } else {
                            for (Photographer p : photographersList) {
                                jComboBox1photographerlist.addItem(p.getName());
                            }
                            jComboBox1photographerlist.setEnabled(true); // Habilitar de nuevo
                        }
                    }
                });
            }
        }).start();
    }
