    private void jButton1contratActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1contratActionPerformed
        String selectedName = (String) jComboBox1photographerlist.getSelectedItem();
        
        if (selectedName == null) {
            JOptionPane.showMessageDialog(this, "Select a photographer first!");
            return;
        }


        double hourlyRate = 0;
        Photographer selectedPhotographer = null;
        
        for (Photographer p : photographersList) {
            if (p.getName().equals(selectedName)) {
                hourlyRate = p.getHourlyRate();
                selectedPhotographer = p;
                break;
            }
        }
 
        if (selectedPhotographer != null) {
            int hours = (int) jSpinner1and5horurs.getValue();
            double totalCost = hourlyRate * hours;
            
   
            String message = String.format(
                "CONTRACT SUMMARY:\n" +
                "Photographer: %s\n" +
                "Rate: $%.2f /hr\n" +
                "Hours: %d\n" +
                "TOTAL TO PAY: $%.2f", 
                selectedName, hourlyRate, hours, totalCost
            );
            
            JOptionPane.showMessageDialog(this, message, "Contract Calculation", JOptionPane.INFORMATION_MESSAGE);
        }
    }//GEN-LAST:event_jButton1contratActionPerformed

