   // 1. Nombre
    String name = lblProductName.getText().trim();

    // 2. Precio base (coma o punto)
    double basePrice = Double.parseDouble(
        lblBasePrice.getText().replace(",", ".")
    );

    // 3. Precio con IVA
    double priceWithVAT = Double.parseDouble(
        lblPriceWithVAT.getText().replace(",", ".")
    );

    // 4. Stock
    int stock = Integer.parseInt(
        lblQuantity.getText().trim()
    );

    // 5. Crear producto
    Product product = new Product(
        name,
        basePrice,
        priceWithVAT,
        stock
    );

    // 6. Guardar en Mongo
    ProductController controller = new ProductController();
    controller.saveProduct(product);
    controller.closeConnection();

    JOptionPane.showMessageDialog(this, "Product saved successfully");

    
