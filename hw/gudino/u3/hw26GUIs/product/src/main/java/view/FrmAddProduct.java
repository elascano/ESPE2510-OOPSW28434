private void enableAutoVATCalculation() {

    lblBasePrice.getDocument().addDocumentListener(new javax.swing.event.DocumentListener() {

        private void calculate() {
            String priceText = lblBasePrice.getText().trim();

            if (priceText.isEmpty()) {
                lblPriceWithVAT.setText("");
                return;
            }

            if (!ProductValidator.isValidBasePrice(priceText)) {
                lblPriceWithVAT.setText("Invalid");
                return;
            }

            double basePrice = ProductValidator.parseBasePrice(priceText);
            double priceWithVAT = TaxCalculator.calculatePriceWithVAT(basePrice);

            lblPriceWithVAT.setText(String.format("%.2f", priceWithVAT));
        }

        @Override
        public void insertUpdate(javax.swing.event.DocumentEvent e) {
            calculate();
        }

        @Override
        public void removeUpdate(javax.swing.event.DocumentEvent e) {
            calculate();
        }

        @Override
        public void changedUpdate(javax.swing.event.DocumentEvent e) {
            calculate();
        }
    });
}
