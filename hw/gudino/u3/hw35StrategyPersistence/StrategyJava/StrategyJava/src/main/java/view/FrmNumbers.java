    private void btnSortActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSortActionPerformed


        String input = txtNumber.getText().trim();

if (!input.matches("\\d+(,\\d+)*")) {
    JOptionPane.showMessageDialog(
        this,
        "Only numbers separated by commas\nExample: 5,3,1,4",
        "Invalid input",
        JOptionPane.ERROR_MESSAGE
    );
    return;
}

String[] parts = input.split(",");
int[] numbers = new int[parts.length];

for (int i = 0; i < parts.length; i++) {
    numbers[i] = Integer.parseInt(parts[i]);
}

SortContext context = new SortContext(numbers, repository);
int[] sorted = context.sort(numbers);

JOptionPane.showMessageDialog(
    this,
    "Algorithm: " + context.getStrategyName()
    + "\nSorted: " + arrayToString(sorted)
);
  
    
    }//GEN-LAST:event_btnSortActionPerformed

    private String arrayToString(int[] arr) {
        StringBuilder sb = new StringBuilder();
        for (int i = 0; i < arr.length; i++) {
            sb.append(arr[i]);
            if (i < arr.length - 1) sb.append(",");
        }
        return sb.toString();
    }
