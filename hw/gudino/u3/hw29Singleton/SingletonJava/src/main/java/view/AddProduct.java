    private void btnAddToStockActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddToStockActionPerformed
                                                 
    String productName = lblAddProduct.getText().trim();
    int quantity = (Integer) spinnerAdd.getValue();

    if (productName.isEmpty() || quantity <= 0) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "Please enter a valid product name and quantity.",
            "Input Error",
            javax.swing.JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Agregar producto al inventario
    controller.addProduct(productName, quantity);
    javax.swing.JOptionPane.showMessageDialog(this,
        "Product added successfully!",
        "Success",
        javax.swing.JOptionPane.INFORMATION_MESSAGE);

    // Limpiar campos
    lblAddProduct.setText("");
    spinnerAdd.setValue(1);
        
    }//GEN-LAST:event_btnAddToStockActionPerformed

